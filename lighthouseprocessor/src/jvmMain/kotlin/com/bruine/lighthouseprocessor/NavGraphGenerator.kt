package com.bruine.lighthouseprocessor

import com.bruine.lighthouse.ScreenType
import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies
import com.squareup.kotlinpoet.*
import com.squareup.kotlinpoet.ksp.toClassName
import com.squareup.kotlinpoet.ksp.writeTo

class NavGraphGenerator(
    private val codeGenerator: CodeGenerator
) {

    fun generateNavGraph(entries: List<DestinationEntry>) {
        val builderFun = FunSpec.builder("addDestinations")
            .receiver(ClassName("androidx.navigation", "NavGraphBuilder"))
            .addParameter("navController", ClassName("androidx.navigation", "NavController"))
            .addParameter(
                ParameterSpec.builder("baseUri", STRING)
                    .defaultValue("\"\"")
                    .build()
            )
            .addKdoc("Auto-generated by Compose Lighthouse ✨")
            .addModifiers(KModifier.PUBLIC)

        // Common members
        val composableMember = MemberName("androidx.navigation.compose", "composable")
        val bottomSheetMember = MemberName("com.bruine.lighthouse", "bottomSheet")
        val toRouteMember = MemberName("androidx.navigation", "toRoute")
        val providerMember = MemberName("androidx.compose.runtime", "CompositionLocalProvider")
        val localNavController = MemberName("com.bruine.lighthouse", "LocalNavController")
        val localRouter = MemberName("com.bruine.lighthouse", "LocalRouter")
        val routerClass = ClassName("com.bruine.lighthouse", "Router")

        entries.forEach { entry ->
            val realRouteClass = entry.routeType?.toClassName() ?: return@forEach
            val screenMember = MemberName(entry.packageName, entry.functionName)
            val functionDecl = entry.declaration

            // Try to find a parameter of type == route type
            val routeParam = functionDecl.parameters.firstOrNull { param ->
                val resolvedType = param.type.resolve().declaration.qualifiedName?.asString()
                resolvedType == realRouteClass.canonicalName
            }
            val routeParamName = routeParam?.name?.asString()

            // Construct deep links list
            val deepLinkPatterns = mutableListOf<String>()

            if (entry.deepLinkPath.isNotBlank()) {
                deepLinkPatterns += """${'$'}{baseUri}/${entry.deepLinkPath}""".replace("//", "/")
            }

            entry.extraDeepLinks.forEach { (deepLinkPath, baseUriOverride) ->
                val uriPrefix = baseUriOverride.ifEmpty { "\${baseUri}" }
                deepLinkPatterns += """${uriPrefix}/${deepLinkPath}""".replace("//", "/")
            }

            val deepLinksBlock = if (deepLinkPatterns.isNotEmpty()) {
                buildString {
                    append("deepLinks = listOf(\n")
                    deepLinkPatterns.forEachIndexed { index, pattern ->
                        append("    navDeepLink { uriPattern = \"$pattern\" }")
                        if (index < deepLinkPatterns.lastIndex) append(",\n")
                    }
                    append("\n)")
                }
            } else null

            val navCall = when (entry.screenType) {
                ScreenType.SHEET ->
                    if (deepLinksBlock != null)
                        "%M<%T>(onDismissRequest = { navController.popBackStack() }, $deepLinksBlock) { backStackEntry ->"
                    else
                        "%M<%T>(onDismissRequest = { navController.popBackStack() }) { backStackEntry ->"
                else ->
                    if (deepLinksBlock != null)
                        "%M<%T>($deepLinksBlock) { backStackEntry ->"
                    else
                        "%M<%T> { backStackEntry ->"
            }

            val block = CodeBlock.builder()
                .addStatement(
                    navCall,
                    if (entry.screenType == ScreenType.SHEET) bottomSheetMember else composableMember,
                    realRouteClass
                )

            if (routeParamName != null) {
                block.addStatement("  val route: %T = backStackEntry.%M()", realRouteClass, toRouteMember)
            }

            // ✅ Create router and provide both locals
            block.addStatement("  val router = %T(navController)", routerClass)
            block.addStatement(
                "  %M(%M provides navController, %M provides router) {",
                providerMember,
                localNavController,
                localRouter
            )

            if (routeParamName != null) {
                block.addStatement("    %M($routeParamName = route)", screenMember)
            } else {
                block.addStatement("    %M()", screenMember)
            }

            block.addStatement("  }")
            block.addStatement("}")
            builderFun.addCode(block.build()).addCode("\n")
        }

        FileSpec.builder("com.bruine.lighthouse.generated", "NavGraph")
            .addFunction(builderFun.build())
            .addImport("androidx.navigation", "NavController", "navDeepLink")
            .addImport("androidx.compose.runtime", "CompositionLocalProvider")
            .addImport("com.bruine.lighthouse", "LocalNavController", "LocalRouter", "Router", "bottomSheet")
            .addImport("androidx.navigation.compose", "composable")
            .build()
            .writeTo(codeGenerator, dependencies = Dependencies.ALL_FILES)
    }
}
