package com.bruine.lighthouseprocessor

import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies
import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.LambdaTypeName
import com.squareup.kotlinpoet.ParameterSpec
import com.squareup.kotlinpoet.ParameterizedTypeName.Companion.parameterizedBy
import com.squareup.kotlinpoet.STRING
import com.squareup.kotlinpoet.UNIT
import com.squareup.kotlinpoet.ksp.writeTo

class NavHostGenerator(
    private val codeGenerator: CodeGenerator
) {

    fun generateNavHost() {
        val packageName = "com.bruine.lighthouse.generated"
        val fileBuilder = FileSpec.builder(packageName, "LighthouseNavHost")
            .addFileComment("Auto-generated by Compose Lighthouse ✨")
            .addImport("androidx.compose.animation", "AnimatedContentTransitionScope")
            .addImport("androidx.compose.animation", "EnterTransition", "ExitTransition")
            .addImport("androidx.compose.runtime", "Composable")
            .addImport("androidx.compose.ui", "Modifier")
            .addImport("androidx.navigation", "NavBackStackEntry", "NavGraphBuilder", "NavHostController")
            .addImport("androidx.navigation.compose", "NavHost", "rememberNavController")
            .addImport("com.bruine.lighthouse", "Route")
            .addImport(packageName, "addDestinations")

        // region → Helper type aliases
        val animatedScope = ClassName("androidx.compose.animation", "AnimatedContentTransitionScope")
        val navBackStackEntry = ClassName("androidx.navigation", "NavBackStackEntry")
        val navGraphBuilder = ClassName("androidx.navigation", "NavGraphBuilder")
        val navHostController = ClassName("androidx.navigation", "NavHostController")
        val enterTransition = ClassName("androidx.compose.animation", "EnterTransition")
        val exitTransition = ClassName("androidx.compose.animation", "ExitTransition")
        val route = ClassName("com.bruine.lighthouse", "Route")
        val modifier = ClassName("androidx.compose.ui", "Modifier")
        // endregion

        // region → Simple version without transitions
        val simpleHost = FunSpec.builder("LighthouseNavHost")
            .addAnnotation(ClassName("androidx.compose.runtime", "Composable"))
            .addModifiers(KModifier.PUBLIC)
            .addParameter(
                ParameterSpec.builder("navController", navHostController)
                    .defaultValue("rememberNavController()")
                    .build()
            )
            .addParameter("startDestination", route)
            .addParameter(
                ParameterSpec.builder("baseUri", STRING)
                    .defaultValue("\"\"")
                    .build()
            )
            .addParameter(
                ParameterSpec.builder("modifier", modifier)
                    .defaultValue("Modifier")
                    .build()
            )
            .addParameter(
                ParameterSpec.builder(
                    "builder",
                    LambdaTypeName.get(receiver = navGraphBuilder, returnType = UNIT)
                )
                    .defaultValue("{}")
                    .build()
            )
            .addCode(
                """
                NavHost(
                    navController = navController,
                    startDestination = startDestination,
                    modifier = modifier,
                ) {
                    addDestinations(navController, baseUri)
                    builder.invoke(this)
                }
                """.trimIndent()
            )
            .build()
        // endregion

        // region → Advanced version with transitions
        val advancedHost = FunSpec.builder("LighthouseNavHost")
            .addAnnotation(ClassName("androidx.compose.runtime", "Composable"))
            .addModifiers(KModifier.PUBLIC)
            .addParameter(
                ParameterSpec.builder("navController", navHostController)
                    .defaultValue("rememberNavController()")
                    .build()
            )
            .addParameter("startDestination", route)
            .addParameter(
                ParameterSpec.builder("baseUri", STRING)
                    .defaultValue("\"\"")
                    .build()
            )
            .addParameter(
                ParameterSpec.builder("modifier", modifier)
                    .defaultValue("Modifier")
                    .build()
            )
            .addParameter(
                ParameterSpec.builder(
                    "enterTransition",
                    LambdaTypeName.get(
                        receiver = animatedScope.parameterizedBy(navBackStackEntry),
                        returnType = enterTransition
                    )
                )
                    .build()
            )
            .addParameter(
                ParameterSpec.builder(
                    "exitTransition",
                    LambdaTypeName.get(
                        receiver = animatedScope.parameterizedBy(navBackStackEntry),
                        returnType = exitTransition
                    )
                )
                    .build()
            )
            .addParameter(
                ParameterSpec.builder(
                    "popEnterTransition",
                    LambdaTypeName.get(
                        receiver = animatedScope.parameterizedBy(navBackStackEntry),
                        returnType = enterTransition
                    )
                )
                    .build()
            )
            .addParameter(
                ParameterSpec.builder(
                    "popExitTransition",
                    LambdaTypeName.get(
                        receiver = animatedScope.parameterizedBy(navBackStackEntry),
                        returnType = exitTransition
                    )
                )
                    .build()
            )
            .addParameter(
                ParameterSpec.builder(
                    "builder",
                    LambdaTypeName.get(receiver = navGraphBuilder, returnType = UNIT)
                )
                    .defaultValue("{}")
                    .build()
            )
            .addCode(
                """
                NavHost(
                    navController = navController,
                    startDestination = startDestination,
                    modifier = modifier,
                    enterTransition = enterTransition,
                    exitTransition = exitTransition,
                    popEnterTransition = popEnterTransition,
                    popExitTransition = popExitTransition,
                ) {
                    addDestinations(navController, baseUri)
                    builder.invoke(this)
                }
                """.trimIndent()
            )
            .build()
        // endregion

        fileBuilder
            .addFunction(simpleHost)
            .addFunction(advancedHost)
            .build()
            .writeTo(codeGenerator, dependencies = Dependencies.ALL_FILES)
    }
}
